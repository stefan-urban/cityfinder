// Builds the game's data files from Natural Earth + world-atlas sources.
//
// Usage:
//   node tools/build-data.mjs <ne_10m_populated_places.geojson> <countries-50m.json>
//
// Sources:
//   https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_10m_populated_places.geojson
//   (the full version, not "_simple": it carries the German names in NAME_DE)
//   https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json
//
// Output is written as plain JS (window globals) so the game works when
// index.html is opened directly from disk (file:// blocks fetch()).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const LARGE_CITY_MIN_POP = 2_000_000;
// Max cities per country. Capitals are always kept (and count toward the
// limit); remaining slots go to the most populous other cities.
const MAX_PER_COUNTRY = 5;

// Shorter English display names for a few verbose Natural Earth country names.
const COUNTRY_EN = {
  "United States of America": "United States",
  "Congo (Kinshasa)": "DR Congo",
  "Congo (Brazzaville)": "Congo",
  "Hong Kong S.A.R.": "Hong Kong",
  "Sao Tome and Principe": "São Tomé and Príncipe",
  "Federated States of Micronesia": "Micronesia",
  "Democratic Republic of the Congo": "DR Congo",
  "Republic of the Congo": "Congo",
  "United Republic of Tanzania": "Tanzania",
};
// German country names come from Intl.DisplayNames (ISO code); these fix the
// gaps (no ISO code) and a few awkward results.
const COUNTRY_DE_BY_ISO = { HK: "Hongkong", BN: "Brunei", CD: "Demokratische Republik Kongo", CG: "Republik Kongo" };
const COUNTRY_DE_BY_NAME = { Somaliland: "Somaliland", Kosovo: "Kosovo" };
// Fixes for individual German city names.
const CITY_DE = { "Aşgabat": "Aschgabat", "New York City": "New York", "Washington": "Washington, D.C." };

const regionDe = new Intl.DisplayNames(["de"], { type: "region" });
const clean = (s) => String(s).replace(/\s+/g, " ").trim();

function germanCountry(p) {
  if (COUNTRY_DE_BY_NAME[p.adm0name]) return COUNTRY_DE_BY_NAME[p.adm0name];
  if (COUNTRY_DE_BY_ISO[p.iso_a2]) return COUNTRY_DE_BY_ISO[p.iso_a2];
  if (/^[A-Z]{2}$/.test(p.iso_a2)) {
    const name = regionDe.of(p.iso_a2);
    if (name && name !== p.iso_a2) return name;
  }
  console.warn(`No German country name for ${p.adm0name} (${p.iso_a2}); using English`);
  return p.adm0name;
}

const [placesPath, worldPath] = process.argv.slice(2);
if (!placesPath || !worldPath) {
  console.error("Usage: node tools/build-data.mjs <places.geojson> <countries-50m.json>");
  process.exit(1);
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "data");
fs.mkdirSync(outDir, { recursive: true });

// ---- Cities ---------------------------------------------------------------
// Normalise property keys to lower case (the full file uses upper case).
const places = JSON.parse(fs.readFileSync(placesPath, "utf8")).features.map((f) =>
  Object.fromEntries(Object.entries(f.properties).map(([k, v]) => [k.toLowerCase(), v]))
);

const seen = new Set();
const candidates = [];
for (const p of places) {
  const capital = p.adm0cap === 1;
  const large = (p.pop_max || 0) >= LARGE_CITY_MIN_POP;
  if (!capital && !large) continue;
  const key = `${p.name}|${p.adm0name}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const nameDe = clean(p.name_de || p.name);
  candidates.push({
    n: clean(p.name),
    nd: CITY_DE[nameDe] || nameDe,
    c: COUNTRY_EN[p.adm0name] || p.adm0name,
    cd: germanCountry(p),
    lat: +p.latitude.toFixed(4),
    lon: +p.longitude.toFixed(4),
    pop: p.pop_max || 0,
    cap: capital ? 1 : 0,
  });
}

// Apply the per-country limit: capitals first, then by population.
const byCountry = new Map(); // keyed by English country name
for (const c of candidates) {
  if (!byCountry.has(c.c)) byCountry.set(c.c, []);
  byCountry.get(c.c).push(c);
}
const cities = [];
let dropped = 0;
for (const list of byCountry.values()) {
  list.sort((a, b) => b.cap - a.cap || b.pop - a.pop);
  const capitals = list.filter((c) => c.cap).length;
  const keep = Math.max(capitals, MAX_PER_COUNTRY);
  cities.push(...list.slice(0, keep));
  dropped += Math.max(0, list.length - keep);
}
cities.sort((a, b) => b.pop - a.pop);

fs.writeFileSync(
  path.join(outDir, "cities.js"),
  "// Generated by tools/build-data.mjs from Natural Earth (public domain).\n" +
    "// Fields: n/nd=name (English/German), c/cd=country (English/German), lat, lon, pop=population (metro), cap=1 if national capital\n" +
    "window.CITYFINDER_CITIES = [\n" +
    cities.map((c) => "  " + JSON.stringify(c)).join(",\n") +
    "\n];\n"
);

// ---- World ----------------------------------------------------------------
const world = fs.readFileSync(worldPath, "utf8");
JSON.parse(world); // validate
fs.writeFileSync(
  path.join(outDir, "world.js"),
  "// Generated by tools/build-data.mjs from world-atlas countries-50m (Natural Earth, public domain).\n" +
    "window.CITYFINDER_WORLD = " + world + ";\n"
);

const caps = cities.filter((c) => c.cap).length;
console.log(`cities: ${cities.length} total, ${caps} capitals, ${cities.length - caps} other large cities (>= ${LARGE_CITY_MIN_POP.toLocaleString()}); ${dropped} dropped by the ${MAX_PER_COUNTRY}-per-country limit`);
